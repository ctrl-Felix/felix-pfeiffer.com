import { messageTotal } from "@/lib/messageCount";
import { routineTotals } from "@/lib/routineUsage";
import { formatMillions, modelName, tokenTotals } from "@/lib/tokenUsage";

const { processed, written, models } = tokenTotals();
const routines = routineTotals();

const modelLines = models.map((item) => `- **${modelName(item.model)}**: ${item.messages} messages, ${formatMillions(item.processed)} tokens, ${formatMillions(item.written)} generated`).join("\n");

const routineLine =
  routines.executions > 0
    ? `\nRoutines that maintain the page on a schedule have used another ${formatMillions(routines.processed)} tokens in ${routines.executions} ${routines.executions === 1 ? "execution" : "executions"}.\n`
    : "";

const tokenLine =
  processed > 0
    ? `\nSo far, building this page has used about ${formatMillions(processed)} tokens, ${formatMillions(written)} of them generated by Claude, from ${messageTotal()} messages written by me. By model:\n\n${modelLines}\n${routineLine}`
    : "";

export const readme = `# README

I'm Felix Pfeiffer, and this is my personal portfolio.

My CV and the about me section are in **Profile**. This file explains what the page itself is about.

Before this project, I wrote all of my code myself. But I was curious how far AI and vibe coding can go. So I decided to vibe code my personal portfolio. That's what this page is.

Not a single line of code on this page was written by me. Claude wrote all of it. All my other code I still write myself. This text is also written by AI, following my instructions.
${tokenLine}`;
